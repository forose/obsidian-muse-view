const DICTS: Record<LangCode, Dict> = { zh: ZH, en: EN };

/** 解析设置中的 language 字段为具体语言代码。 */
export function resolveLang(language: string, appLang: string): LangCode {
  if (language === "zh" || language === "en") return language;
  return appLang?.toLowerCase().startsWith("zh") ? "zh" : "en";
}

/**
 * 读取 Obsidian 当前语言。
 * 部分 obsidian 类型版本未声明 `App.getLocale()`，这里做运行时兼容。
 */
export function getAppLocale(app: App): string {
  const fn = (app as unknown as { getLocale?: () => string }).getLocale;
  return typeof fn === "function" ? fn.call(app) : "en";
}

/** 翻译函数；支持 {name} 占位符；缺失时回退到 key。 */
export function createT(lang: LangCode) {
  const dict = DICTS[lang];
  return (key: string, vars?: Record<string, string | number>): string => {
    let s = dict[key] ?? ZH[key] ?? key;
    if (vars) {
      for (const [k, v] of Object.entries(vars)) {
        s = s.replace(new RegExp(`\\{${k}\\}`, "g"), String(v));
      }
    }
    return s;
  };
}

export type T = ReturnType<typeof createT>;
